const DICCIONARIOS = { es: ES, en: EN }

// si el usuario activó "reducir movimiento" en su sistema,
// no se hacen animaciones de máquina de escribir ni apariciones suaves.
const reduceMotion = window.matchMedia(
  '(prefers-reduced-motion: reduce)'
).matches
let idiomaActual = 'es'
let tipeoTimer = null

// efecto de máquina de escribir para el rol del hero.
// borra el texto anterior y va pintando letra por letra.
function escribirMaquina (contenedor, texto) {
  const zona = contenedor.querySelector('.typed')
  if (!zona) {
    contenedor.textContent = texto
    return
  }

  if (tipeoTimer) {
    clearInterval(tipeoTimer)
    tipeoTimer = null
  }
  if (reduceMotion) {
    zona.textContent = texto
    return
  }

  zona.textContent = ''
  let i = 0
  tipeoTimer = setInterval(() => {
    i += 1
    zona.textContent = texto.slice(0, i)
    if (i >= texto.length) {
      clearInterval(tipeoTimer)
      tipeoTimer = null
    }
  }, 34)
}

// aplica el idioma elegido a todo el sitio.
// toca textos, atributos alt, aria-labels, título y meta description.
function aplicarIdioma (idioma) {
  const textos = DICCIONARIOS[idioma]
  if (!textos) return
  idiomaActual = idioma

  // textos visibles con data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const clave = el.getAttribute('data-i18n')
    const valor = textos[clave]
    if (valor === undefined) {
      console.warn('falta traducción:', clave)
      return
    }
    if (el.hasAttribute('data-typewriter')) escribirMaquina(el, valor)
    else el.textContent = valor
  })

  // alt de imágenes traducibles
  document.querySelectorAll('[data-i18n-alt]').forEach(el => {
    const valor = textos[el.getAttribute('data-i18n-alt')]
    if (valor !== undefined) el.setAttribute('alt', valor)
  })

  // aria-labels traducibles
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    const valor = textos[el.getAttribute('data-i18n-aria')]
    if (valor !== undefined) el.setAttribute('aria-label', valor)
  })

  // aria-label del botón hamburguesa
  document
    .querySelector('.nav-responsive')
    .setAttribute('aria-label', textos['aria.menu'])

  // título de la pestaña y descripción para seo
  document.title = textos['meta.title']
  const metaDesc = document.querySelector('meta[name="description"]')
  if (metaDesc) metaDesc.setAttribute('content', textos['meta.description'])

  document.documentElement.lang = idioma

  // actualizar visualmente el botón ES/EN
  const boton = document.getElementById('btn-idioma')
  const otro = idioma === 'es' ? 'en' : 'es'
  boton.innerHTML =
    '<span class="idioma-activo">' +
    idioma.toUpperCase() +
    '</span>' +
    '<span class="idioma-sep">/</span>' +
    '<span class="idioma-inactivo">' +
    otro.toUpperCase() +
    '</span>'
  boton.setAttribute(
    'aria-label',
    idioma === 'es' ? 'Switch to English' : 'Cambiar a español'
  )

  // guardar preferencia para la próxima visita
  try {
    localStorage.setItem('idioma', idioma)
  } catch (e) {
    /* modo privado */
  }
}

function cambiarIdioma () {
  aplicarIdioma(idiomaActual === 'es' ? 'en' : 'es')
}

// menú móvil: abrir y cerrar el panel con el botón hamburguesa
const navEl = document.getElementById('nav')
const btnMenu = document.querySelector('.nav-responsive')
const iconoMenu = btnMenu.querySelector('i')

function cerrarMenu () {
  navEl.classList.remove('responsive')
  btnMenu.setAttribute('aria-expanded', 'false')
  iconoMenu.classList.add('fa-bars')
  iconoMenu.classList.remove('fa-xmark')
}

function mostrarOcultarMenu () {
  const abierto = navEl.classList.toggle('responsive')
  btnMenu.setAttribute('aria-expanded', String(abierto))
  iconoMenu.classList.toggle('fa-bars', !abierto)
  iconoMenu.classList.toggle('fa-xmark', abierto)
}

btnMenu.addEventListener('click', mostrarOcultarMenu)
document.getElementById('btn-idioma').addEventListener('click', cambiarIdioma)

// el menú se cierra solo cuando el usuario hace clic en un enlace,
// presiona escape, toca fuera del panel o agranda la pantalla
navEl
  .querySelectorAll('a')
  .forEach(a => a.addEventListener('click', cerrarMenu))
document.addEventListener('keydown', e => {
  if (e.key === 'Escape') cerrarMenu()
})
document.addEventListener('click', e => {
  if (
    navEl.classList.contains('responsive') &&
    !navEl.contains(e.target) &&
    !btnMenu.contains(e.target)
  ) {
    cerrarMenu()
  }
})
window.addEventListener('resize', () => {
  if (window.innerWidth > 980) cerrarMenu()
})

