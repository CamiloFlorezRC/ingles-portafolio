// cuenta animada del porcentaje y llena la barra de cada habilidad
function animarConteo (el, objetivo, duracion) {
  if (reduceMotion) {
    el.textContent = objetivo + '%'
    return
  }
  const inicio = performance.now()
  function paso (t) {
    const p = Math.min((t - inicio) / duracion, 1)
    // easing cúbico para que el número no suba lineal
    const eased = 1 - Math.pow(1 - p, 3)
    el.textContent = Math.round(objetivo * eased) + '%'
    if (p < 1) requestAnimationFrame(paso)
  }
  requestAnimationFrame(paso)
}

function animarHabilidades () {
  const barras = document.querySelectorAll('.progreso')

  const mostrar = barra => {
    const porcentaje = parseInt(barra.getAttribute('data-percent') || '0', 10)
    barra.style.width = porcentaje + '%'
    const etiqueta = barra.closest('.skill').querySelector('.skill-porc')
    if (etiqueta) animarConteo(etiqueta, porcentaje, 1200)
  }

  if (!('IntersectionObserver' in window)) {
    barras.forEach(mostrar)
    return
  }

  const observador = new IntersectionObserver(
    (entradas, obs) => {
      entradas.forEach(entrada => {
        if (entrada.isIntersecting) {
          mostrar(entrada.target)
          obs.unobserve(entrada.target)
        }
      })
    },
    { threshold: 0.25, rootMargin: '0px 0px -10% 0px' }
  )

  barras.forEach(barra => observador.observe(barra))
}

