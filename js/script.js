// resalta el enlace del navbar según la sección visible en pantalla
const enlacesNav = navEl.querySelectorAll('a[href^="#"]')

function activarEnlace (id) {
  enlacesNav.forEach(a => {
    const activo = a.getAttribute('href') === '#' + id
    a.classList.toggle('activo', activo)
    if (activo) a.setAttribute('aria-current', 'true')
    else a.removeAttribute('aria-current')
  })
}

if ('IntersectionObserver' in window) {
  const spy = new IntersectionObserver(
    entradas => {
      entradas.forEach(en => {
        if (en.isIntersecting) activarEnlace(en.target.id)
      })
    },
    { rootMargin: '-40% 0px -55% 0px' }
  )
  document.querySelectorAll('section[id]').forEach(s => spy.observe(s))
}

// hace que las secciones aparezcan con fade al hacer scroll
if ('IntersectionObserver' in window) {
  const revelador = new IntersectionObserver(
    (entradas, obs) => {
      entradas.forEach(en => {
        if (en.isIntersecting) {
          en.target.classList.add('visible')
          obs.unobserve(en.target)
        }
      })
    },
    { threshold: 0.12, rootMargin: '0px 0px -6% 0px' }
  )
  document
    .querySelectorAll('[data-reveal]')
    .forEach(el => revelador.observe(el))
} else {
  // fallback: si el navegador no soporta observer, se muestra todo de una
  document
    .querySelectorAll('[data-reveal]')
    .forEach(el => el.classList.add('visible'))
}

